-- 로컬 Oracle: 과제 제공 환경과 같은 조건을 재현한다 (D-14).
-- - 테이블은 고객사 스키마(TOTO)가 소유하고, 앱 계정(APPLICANT)은 SELECT·INSERT·UPDATE만 가진다. DELETE·DDL 불가.
-- - 앱은 스키마 접두어 없이 ORDER_TB, SHIPMENT_TB로 접근한다 (동의어).
-- 컨테이너를 처음 만들 때 SYS로 한 번 실행된다.

ALTER SESSION SET CONTAINER = FREEPDB1;

-- 테이블 소유 스키마. 접속 권한이 없어 앱이 이 계정으로 붙는 일은 없다.
CREATE USER TOTO IDENTIFIED BY "toto_owner_local" QUOTA UNLIMITED ON USERS;

CREATE TABLE TOTO.ORDER_TB (
	ORDER_ID      VARCHAR2(100 BYTE) NOT NULL,
	APPLICANT_KEY VARCHAR2(100 BYTE) NOT NULL,
	USER_ID       VARCHAR2(100 BYTE),
	ITEM_ID       VARCHAR2(100 BYTE),
	NAME          VARCHAR2(100 BYTE),
	ADDRESS       VARCHAR2(100 BYTE),
	ITEM_NAME     VARCHAR2(100 BYTE),
	PRICE         VARCHAR2(100 BYTE),
	STATUS        VARCHAR2(100 BYTE),
	CONSTRAINT ORDER_TB_PK PRIMARY KEY (ORDER_ID, APPLICANT_KEY)
);

CREATE TABLE TOTO.SHIPMENT_TB (
	SHIPMENT_ID   VARCHAR2(100 BYTE) NOT NULL,
	APPLICANT_KEY VARCHAR2(100 BYTE) NOT NULL,
	ORDER_ID      VARCHAR2(100 BYTE),
	ITEM_ID       VARCHAR2(100 BYTE),
	ADDRESS       VARCHAR2(100 BYTE),
	CONSTRAINT SHIPMENT_TB_PK PRIMARY KEY (SHIPMENT_ID, APPLICANT_KEY)
);

-- 앱 계정 (지원자 공용 계정)
CREATE USER APPLICANT IDENTIFIED BY "applicant_local";
GRANT CREATE SESSION TO APPLICANT;
GRANT SELECT, INSERT, UPDATE ON TOTO.ORDER_TB TO APPLICANT;
GRANT SELECT, INSERT, UPDATE ON TOTO.SHIPMENT_TB TO APPLICANT;
CREATE SYNONYM APPLICANT.ORDER_TB FOR TOTO.ORDER_TB;
CREATE SYNONYM APPLICANT.SHIPMENT_TB FOR TOTO.SHIPMENT_TB;
