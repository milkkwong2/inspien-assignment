-- 처리 이력 DB (H2, 앱 소유). 기동마다 실행하므로 모두 IF NOT EXISTS로 쓴다 (설계서 §4.2, D-19).
-- 단계별 진행(ORDER_STAGE)은 Oracle에 담을 곳이 없어 여기에만 있다. Oracle STATUS(N/Y)의 사본은 두지 않는다 (D-26).

-- 받은 메시지 1건. 중복 판단, 재전송 시 이전 응답 반환, 거부 사유 (D-05, D-07, D-16, D-24)
CREATE TABLE IF NOT EXISTS RECEIVED_MESSAGE (
	ID              VARCHAR(13)              PRIMARY KEY,  -- TSID = 메시지 ID
	MESSAGE_KEY     VARCHAR(64)              NOT NULL,     -- 본문 SHA-256. 유일 제약 없음 (완료 1분 뒤 같은 값이 새 메시지로 올 수 있다)
	RECEIVED_AT     TIMESTAMP WITH TIME ZONE NOT NULL,     -- 요청 도착 시각
	CONTENT_TYPE    VARCHAR(255),                          -- 길이를 바꾸면 ContentTypeLimit.MAX_LENGTH도 바꾼다 (넘으면 수신 400)
	RAW_BODY        BLOB                     NOT NULL,     -- 받은 바이트 그대로
	STATE           VARCHAR(20)              NOT NULL,     -- PROCESSING, COMPLETED, FAILED
	RESPONSE_STATUS INT,
	RESPONSE_BODY   CLOB,
	COMPLETED_AT    TIMESTAMP WITH TIME ZONE,              -- 중복 판단 1분 창의 기준
	CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,     -- 공통 시각 필드 (D-27)
	UPDATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS RECEIVED_MESSAGE_KEY_ID_IDX ON RECEIVED_MESSAGE (MESSAGE_KEY, ID);  -- 같은 키의 가장 최근 기록 (ID 역순 1건)
CREATE INDEX IF NOT EXISTS RECEIVED_MESSAGE_STATE_IDX ON RECEIVED_MESSAGE (STATE, ID);

-- 메시지 → 미리 배정한 주문번호. 재처리 시 같은 번호 재사용, 영수증의 수신일시 (D-05, D-09, D-16)
CREATE TABLE IF NOT EXISTS MESSAGE_ORDER (
	ORDER_ID    VARCHAR(4)               PRIMARY KEY,
	MESSAGE_ID  VARCHAR(13)              NOT NULL REFERENCES RECEIVED_MESSAGE (ID),
	SEQ         INT                      NOT NULL,         -- 메시지 안 ITEM 순서
	USER_ID     VARCHAR(100),
	ITEM_ID     VARCHAR(100),
	RECEIVED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
	CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
	UPDATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
	CONSTRAINT MESSAGE_ORDER_SEQ_UK UNIQUE (MESSAGE_ID, SEQ)
);

-- 주문 × 단계의 진행 상태: 단계 완료, 사람이 확인 표시, 재시도, 배송 번호 미리 배정 (D-03, D-10, D-12, D-26)
-- 단계 상태 PENDING·DONE·FAILED는 저장하지 않고 COMPLETED_AT·REACHED_FAILED에서 계산한다
-- 수신 기록이 없는 주문도 FAILED 표시를 남겨야 하므로 MESSAGE_ORDER에 외래키를 걸지 않는다 (D-22)
CREATE TABLE IF NOT EXISTS ORDER_STAGE (
	ORDER_ID        VARCHAR(4)               NOT NULL,
	STAGE           VARCHAR(20)              NOT NULL,     -- RECEIPT, SHIPMENT
	ATTEMPTS        INT                      DEFAULT 0 NOT NULL,
	NEXT_ATTEMPT_AT TIMESTAMP WITH TIME ZONE,
	REACHED_FAILED  BOOLEAN                  DEFAULT FALSE NOT NULL,  -- 사람이 확인: 자동 처리 멈춤
	LAST_ERROR      VARCHAR(1000),
	ARTIFACT        VARCHAR(255),                          -- 파일명 또는 미리 배정한 SHIPMENT_ID
	COMPLETED_AT    TIMESTAMP WITH TIME ZONE,              -- 단계 완료 시각
	CREATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
	UPDATED_AT      TIMESTAMP WITH TIME ZONE NOT NULL,
	PRIMARY KEY (ORDER_ID, STAGE)
);

-- 일어난 일 1건. 추가만 한다 (D-13, D-22)
-- 이력은 최선 노력이라, 기록이 제약 위반으로 사라지지 않도록 외래키를 걸지 않는다
CREATE TABLE IF NOT EXISTS PROCESS_EVENT (
	ID          VARCHAR(13)              PRIMARY KEY,      -- TSID
	OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
	MESSAGE_ID  VARCHAR(13),
	ORDER_ID    VARCHAR(4),
	STAGE       VARCHAR(20),
	RESULT      VARCHAR(30)              NOT NULL,
	DETAIL      VARCHAR(2000),
	CREATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL,
	UPDATED_AT  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS PROCESS_EVENT_ORDER_IDX ON PROCESS_EVENT (ORDER_ID, ID);
CREATE INDEX IF NOT EXISTS PROCESS_EVENT_MESSAGE_IDX ON PROCESS_EVENT (MESSAGE_ID, ID);

-- 기존 H2 파일 마이그레이션. CREATE TABLE IF NOT EXISTS는 있는 테이블에 컬럼을 더하지 않는다 (D-26, D-27).
-- 기존 행은 마이그레이션한 시각으로 채워진다. 새 파일에서는 아무 일도 하지 않는다
ALTER TABLE RECEIVED_MESSAGE ADD COLUMN IF NOT EXISTS CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;
ALTER TABLE RECEIVED_MESSAGE ADD COLUMN IF NOT EXISTS UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;
ALTER TABLE MESSAGE_ORDER ADD COLUMN IF NOT EXISTS CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;
ALTER TABLE MESSAGE_ORDER ADD COLUMN IF NOT EXISTS UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;
ALTER TABLE ORDER_STAGE ADD COLUMN IF NOT EXISTS COMPLETED_AT TIMESTAMP WITH TIME ZONE;
ALTER TABLE ORDER_STAGE ADD COLUMN IF NOT EXISTS CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;
ALTER TABLE PROCESS_EVENT ADD COLUMN IF NOT EXISTS CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;
ALTER TABLE PROCESS_EVENT ADD COLUMN IF NOT EXISTS UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;

